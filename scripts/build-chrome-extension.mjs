#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const rootDirectory = path.resolve(scriptDirectory, '..');
const sourceDirectory = path.join(rootDirectory, 'ChromeExtension');
const outputDirectory = path.join(rootDirectory, 'dist', 'ChromeExtension');

const read = name => fs.readFileSync(path.join(sourceDirectory, name), 'utf8');
const indent = source => source.split('\n').map(line => `  ${line}`).join('\n');

const background = read('background.js')
  .replaceAll("files: ['video-element.js']", "files: ['piply.js']");

const entries = [
  ['runBackground', background],
  ['runOffscreen', read('offscreen.js')],
  ['runPopup', read('popup.js')],
  ['runVideoElement', read('video-element.js')]
];

const bundle = `// Generated by scripts/build-chrome-extension.mjs. Do not edit.\n'use strict';\n\n${entries
  .map(([name, source]) => `function ${name}() {\n${indent(source)}\n}`)
  .join('\n\n')}\n\n(() => {\n  if (typeof window === 'undefined') {\n    runBackground();\n    return;\n  }\n\n  const isExtensionPage = window.location.protocol === 'chrome-extension:';\n  if (isExtensionPage && window.location.pathname.endsWith('/offscreen.html')) {\n    runOffscreen();\n  } else if (isExtensionPage && window.location.pathname.endsWith('/popup.html')) {\n    runPopup();\n  } else {\n    // This branch runs only when piply.js is injected into the selected web page.\n    runVideoElement();\n  }\n})();\n`;

const manifest = JSON.parse(read('manifest.json'));
manifest.background.service_worker = 'piply.js';

const replaceScript = html => html
  .replace('src="offscreen.js"', 'src="piply.js"')
  .replace('src="popup.js"', 'src="piply.js"');

fs.rmSync(outputDirectory, { recursive: true, force: true });
fs.mkdirSync(outputDirectory, { recursive: true });
fs.writeFileSync(path.join(outputDirectory, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
fs.writeFileSync(path.join(outputDirectory, 'piply.js'), bundle);
fs.writeFileSync(path.join(outputDirectory, 'offscreen.html'), replaceScript(read('offscreen.html')));
fs.writeFileSync(path.join(outputDirectory, 'popup.html'), replaceScript(read('popup.html')));
fs.copyFileSync(path.join(sourceDirectory, 'popup.css'), path.join(outputDirectory, 'popup.css'));

console.log(`Built Chrome extension: ${outputDirectory}`);
console.log('JavaScript files: 1 (piply.js)');

